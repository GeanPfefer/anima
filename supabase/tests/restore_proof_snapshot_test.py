def crlf_violation(data: bytes, autocrlf: str) -> bool:
    """Allow only uniform checkout CRLF with an explicitly compatible Git mode."""
    if b'\r' not in data:
        return False
    remainder = data.replace(b'\r\n', b'')
    return autocrlf not in ('true', 'input') or b'\r' in remainder or b'\n' in remainder


def run(args, **kwargs):
    return subprocess.run(args, text=True, capture_output=True, timeout=30, **kwargs)


class FormatTests(unittest.TestCase):
    def test_lf(self):
        self.assertFalse(crlf_violation(b'a\nb\n', 'false'))

    def test_crlf_true(self):
        self.assertFalse(crlf_violation(b'a\r\nb\r\n', 'true'))

    def test_crlf_input(self):
        self.assertFalse(crlf_violation(b'a\r\nb\r\n', 'input'))

    def test_crlf_false(self):
        self.assertTrue(crlf_violation(b'a\r\nb\r\n', 'false'))

    def test_mixed(self):
        self.assertTrue(crlf_violation(b'a\r\nb\n', 'true'))

    def test_bare_cr(self):
        self.assertTrue(crlf_violation(b'a\rb\n', 'input'))

    def test_files_format(self):
        result = run(['git', 'config', '--get', 'core.autocrlf'], cwd=ROOT)
        autocrlf = result.stdout.strip().lower() if result.returncode == 0 else ''
        for path in PATHS:
            with self.subTest(path=path.name):
                data = path.read_bytes()
                self.assertTrue(data.endswith(b'\n'))
                self.assertFalse(crlf_violation(data, autocrlf))

    def test_readme(self):
        content = (PROOF / 'README.md').read_text()
        for word in SQL_NAMES + ('read-only', 'stale', '20260928000003'):
            self.assertIn(word, content)

    def test_static_read_only(self):
        for name in SQL_NAMES:
            sql = (PROOF / name).read_text()
            # Remove comments and SQL string literals, including generated SQL
            # only for literals; separately inspect generated dollar blocks below.
            sql = re.sub(r'/\*.*?\*/|--[^\n]*', '', sql, flags=re.S)
            self.assertNotRegex(sql.lower(), r'\b(?:rolpassword|pg_authid)\b')
            scrubbed = re.sub(r"'(?:''|[^'])*'", "''", sql)
            self.assertNotRegex(scrubbed, r'(?i)\b(?:INSERT|UPDATE|DELETE|CREATE|DROP|ALTER|TRUNCATE|GRANT|REVOKE|COPY)\b')
            self.assertTrue(sql.startswith('\\set ON_ERROR_STOP 1\nSET default_transaction_read_only = on;\nBEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY;'))
            self.assertTrue(sql.rstrip().endswith('COMMIT;'))


