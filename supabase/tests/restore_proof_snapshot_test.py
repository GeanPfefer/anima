    def test_active_backend(self):
        args = ['docker', 'exec', '-i', self.main, 'psql', '-U', 'postgres', '-h', 'localhost',
                '-X', '-A', '-t', '-q', '-v', 'ON_ERROR_STOP=1', '-d', 'proof_a']
        process = subprocess.Popen(args, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        try:
            process.stdin.write('SELECT pg_sleep(10);\n')
            process.stdin.close()
            deadline = time.monotonic() + 5
            while time.monotonic() < deadline:
                active = self.execute("SELECT count(*) FROM pg_stat_activity WHERE datname=current_database() AND pid<>pg_backend_pid() AND state='active' AND query LIKE 'SELECT pg_sleep%';")
                if int(active) > 0:
                    break
                time.sleep(0.1)
            else:
                self.fail('Synthetic sleeping backend never became active')
            self.assert_failure(self.gate(), 'backends_active')
        finally:
            process.wait(timeout=15)
            process.stdout.close()
            process.stderr.close()

    def test_recent_event_and_zero_window(self):
        self.execute('UPDATE public.work_events SET created_at=now();')
        try:
            self.assert_failure(self.gate(), 'recent_events')
            result = self.gate(variables=('min_quiet_seconds=0',))
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn('quiet_window_s=0', result.stdout)
            self.assertIn('quiescence_verdict=PASS', result.stdout)
        finally:
            self.execute("UPDATE public.work_events SET created_at='2001-01-01 00:00:00+00';")

    def test_empty_ledger_fails(self):
        self.execute('DELETE FROM public.work_events;')
        try:
            self.assert_failure(self.gate(variables=('min_quiet_seconds=0',)), 'recent_events')
        finally:
            self.execute("INSERT INTO public.work_events(seq,created_at) VALUES(1,'2001-01-01 00:00:00+00');")

    def test_privacy_and_grammar(self):
        grammar = re.compile(r'(?:table:[^=\s]+=[0-9]+:[0-9a-f]{64}|coverage_tables_in_scope=[0-9]+|fk_orphans:[^=\s]+=[0-9]+|(?:constraints|indexes|columns)=[0-9]+:[0-9a-f]{64}|sequence:[^=\s]+=-?[0-9]+:[tf])')
        for line in self.snapshot():
            self.assertIsNotNone(grammar.fullmatch(line), line)
        for name in SQL_NAMES:
            result = self.tool(name)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertNotIn('ZZSENTINELA_DADO_PRIVADO', result.stdout + result.stderr)
            self.assertNotIn('ZZSENTINELA_HASH', result.stdout + result.stderr)

    def test_read_only_unchanged(self):
        before = self.snapshot()
        counts = self.execute('SELECT (SELECT count(*) FROM private.proof_data), (SELECT count(*) FROM public.work_claims), (SELECT count(*) FROM public.work_events);')
        for name in SQL_NAMES:
            result = self.tool(name)
            self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.snapshot(), before)
        self.assertEqual(self.execute('SELECT (SELECT count(*) FROM private.proof_data), (SELECT count(*) FROM public.work_claims), (SELECT count(*) FROM public.work_events);'), counts)


