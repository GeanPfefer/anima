class SnapshotTests(unittest.TestCase):
    containers = []

    @classmethod
    def cleanup(cls):
        for name in list(cls.containers):
            if not re.fullmatch(r'anima-restore-proof-test-[0-9a-f]{8}', name):
                raise RuntimeError('Refusing cleanup of a non-synthetic container')
            try:
                run(['docker', 'rm', '-f', name])
            except (OSError, subprocess.TimeoutExpired):
                pass
            cls.containers.remove(name)

    @classmethod
    def unavailable(cls, message):
        cls.cleanup()
        if os.environ.get('ANIMA_RESTORE_PROOF_ALLOW_SKIP') == '1':
            raise unittest.SkipTest(message)
        raise RuntimeError(message)

    @classmethod
    def start_container(cls):
        name = 'anima-restore-proof-test-' + uuid.uuid4().hex[:8]
        if not re.fullmatch(r'anima-restore-proof-test-[0-9a-f]{8}', name):
            raise RuntimeError('Refusing a non-synthetic container')
        cls.containers.append(name)
        result = run(['docker', 'run', '--pull=never', '--rm', '-d', '-e',
                      'POSTGRES_PASSWORD=' + secrets.token_hex(24), '--name', name, IMAGE])
        if result.returncode:
            cls.unavailable('Cannot start isolated PostgreSQL image: ' + result.stderr)
        deadline = time.monotonic() + 90
        while time.monotonic() < deadline:
            ready = run(['docker', 'exec', name, 'pg_isready', '-U', 'postgres', '-h', 'localhost'])
            if ready.returncode == 0:
                return name
            time.sleep(0.25)
        cls.unavailable('Isolated PostgreSQL did not become ready within 90 seconds')

    @classmethod
    def psql(cls, sql, db='proof_a', container=None, variables=()):
        name = container or cls.main
        if not re.fullmatch(r'anima-restore-proof-test-[0-9a-f]{8}', name):
            raise RuntimeError('Refusing database access outside a synthetic container')
        args = ['docker', 'exec', '-i', name, 'psql', '-U', 'postgres', '-h', 'localhost',
                '-X', '-A', '-t', '-q', '-v', 'ON_ERROR_STOP=1', '-d', db]
        for variable in variables:
            args.extend(['-v', variable])
        return run(args, input=sql)

    @classmethod
    def execute(cls, sql, db='proof_a'):
        result = cls.psql(sql, db)
        if result.returncode:
            raise AssertionError('Synthetic SQL failed: ' + result.stderr)
        return result.stdout.strip()

    @classmethod
    def setUpClass(cls):
        atexit.register(cls.cleanup)
        if not shutil.which('docker'):
            cls.unavailable('Docker unavailable; isolated restore proof cannot run')
        try:
            info = run(['docker', 'info'])
            if info.returncode:
                cls.unavailable('Docker daemon unavailable: ' + info.stderr)
            image = run(['docker', 'image', 'inspect', IMAGE])
            if image.returncode:
                cls.unavailable('Required local image missing; network pull is disabled: ' + IMAGE)
            cls.main = cls.start_container()
            cls.missing = cls.start_container()
            bootstrap = """
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticator') THEN
  CREATE ROLE authenticator NOLOGIN;
 END IF;
END $$;
CREATE ROLE anima_system_writer NOLOGIN NOINHERIT;
GRANT anima_system_writer TO authenticator;
CREATE ROLE proof_login LOGIN PASSWORD 'SyntheticRolePhrase123';
ALTER ROLE proof_login SET statement_timeout = '7s';
CREATE DATABASE proof_a TEMPLATE template0;
CREATE DATABASE proof_b TEMPLATE template0;
"""
            cls.execute(bootstrap, 'postgres')
            for db, rows in (('proof_a', ROWS), ('proof_b', tuple(reversed(ROWS)))):
                cls.execute(FIXTURE + '\nINSERT INTO private.proof_data VALUES ' + ','.join(rows) + ';', db)
        except BaseException:
            cls.cleanup()
            raise

    @classmethod
    def tearDownClass(cls):
        cls.cleanup()

    def tool(self, name='memory-snapshot.sql', db='proof_a', prefix='', variables=(), container=None):
        return self.psql(prefix + (PROOF / name).read_text(), db, container, variables)

    def snapshot(self, db='proof_a', prefix=''):
        result = self.tool(db=db, prefix=prefix)
        self.assertEqual(result.returncode, 0, result.stderr)
        return sorted(result.stdout.splitlines())

    def changed(self, sql, expected):
        before = self.snapshot()
        # Mutations exist only in an outer transaction; run the projection
        # inside that transaction and rollback the synthetic changes.
        source = (PROOF / 'memory-snapshot.sql').read_text()
        source = source.replace('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY;',
                                '').replace('COMMIT;', 'ROLLBACK;')
        result = self.psql('BEGIN ISOLATION LEVEL REPEATABLE READ;\n' + sql + '\n' + source)
        self.assertEqual(result.returncode, 0, result.stderr)
        after = sorted(result.stdout.splitlines())
        delta = [line.split('=')[0] for line in set(before).symmetric_difference(after)]
        self.assertEqual(set(delta), set(expected))
        self.assertEqual(self.snapshot(), before)

    def gate(self, prefix='', variables=()):
        return self.tool('quiescence-gate.sql', prefix=prefix, variables=variables)

    def assert_failure(self, result, code):
        self.assertEqual(result.returncode, 3, result.stderr)
        self.assertIn('quiescence_verdict=FAIL', result.stdout)
        failures = next(line for line in result.stdout.splitlines() if line.startswith('quiescence_failures='))
        self.assertIn(code, failures.split('=', 1)[1].split(','))

    def test_determinism(self):
        self.assertEqual(self.snapshot(), self.snapshot())

    def test_insertion_order(self):
        self.assertEqual(self.snapshot(), self.snapshot('proof_b'))

    def test_cell(self):
        self.changed("UPDATE private.proof_data SET text_col='changed' WHERE id=2;", ['table:private.proof_data'])

    def test_null_to_empty(self):
        self.changed("UPDATE private.proof_data SET text_col='' WHERE id=1;", ['table:private.proof_data'])

    def test_vector(self):
        self.changed("UPDATE private.proof_data SET vec_col='[1,2,4]' WHERE id=1;", ['table:private.proof_data'])

    def test_json(self):
        self.changed("UPDATE private.proof_data SET json_col=jsonb_set(json_col,'{a}','9') WHERE id=1;", ['table:private.proof_data'])

    def test_bytea(self):
        self.changed("UPDATE private.proof_data SET blob_col=decode('0002ff','hex') WHERE id=1;", ['table:private.proof_data'])

    def test_array(self):
        self.changed('UPDATE private.proof_data SET arr_col=ARRAY[1,3] WHERE id=1;', ['table:private.proof_data'])

    def test_fk_orphan(self):
        self.changed('SET session_replication_role=replica; INSERT INTO private.proof_data(id,parent_id) VALUES(9,999);',
                     ['table:private.proof_data', 'fk_orphans:private.proof_data.proof_data_parent_id_fkey'])
        self.execute('SET session_replication_role=replica; INSERT INTO private.proof_data(id,parent_id) VALUES(9,999);')
        try:
            self.assertIn('fk_orphans:private.proof_data.proof_data_parent_id_fkey=1', self.snapshot())
        finally:
            self.execute('DELETE FROM private.proof_data WHERE id=9;')

    def test_composite_fk_simple(self):
        self.assertIn('fk_orphans:private.proof_composite_child.proof_pair_fk=0', self.snapshot())
        self.changed('SET session_replication_role=replica; INSERT INTO private.proof_composite_child VALUES (99,99);',
                     ['table:private.proof_composite_child', 'fk_orphans:private.proof_composite_child.proof_pair_fk'])

    def test_column(self):
        self.changed('ALTER TABLE private.proof_data ADD COLUMN extra_col integer;', ['columns', 'table:private.proof_data'])

    def test_index(self):
        self.changed('CREATE INDEX proof_text_idx ON private.proof_data(text_col);', ['indexes'])

    def test_constraint(self):
        self.changed('ALTER TABLE private.proof_data ADD CONSTRAINT proof_positive CHECK (id > 0);', ['constraints'])

    def test_sequence(self):
        before = self.snapshot()
        try:
            self.execute("SELECT setval('public.work_events_seq_seq', 77, true);")
            after = self.snapshot()
            self.assertIn('sequence:public.work_events_seq_seq=77:t', after)
            self.assertEqual({line.split('=')[0] for line in set(before) ^ set(after)}, {'sequence:public.work_events_seq_seq'})
        finally:
            self.execute("SELECT setval('public.work_events_seq_seq', 1, false);")

    def test_coverage(self):
        lines = self.snapshot()
        self.assertIn('coverage_tables_in_scope=' + str(sum(line.startswith('table:') for line in lines)), lines)
        self.execute('CREATE TABLE private.proof_new (id integer);')
        try:
            lines = self.snapshot()
            self.assertTrue(any(line.startswith('table:private.proof_new=0:') for line in lines))
            self.assertIn('coverage_tables_in_scope=' + str(sum(line.startswith('table:') for line in lines)), lines)
        finally:
            self.execute('DROP TABLE private.proof_new;')

    def test_roles_projection(self):
        result = self.tool('roles-projection.sql')
        self.assertEqual(result.returncode, 0, result.stderr)
        for text in ('role|anima_system_writer|login=false|inherit=false',
                     'membership|anima_system_writer|member=authenticator|admin=false',
                     'writer_schema_usage|private|true', 'writer_exec|private.proof_fn(integer)|secdef=true',
                     'writer_table|private.proof_data|SELECT', 'writer_table|private.proof_data|INSERT',
                     'writer_table|private.proof_data|UPDATE', 'writer_table|private.proof_data|DELETE',
                     'role_setting|proof_login|<all>|statement_timeout=7s',
                     'auth_users_by_role|authenticated|1', 'auth_users_by_role|<null>|1'):
            self.assertIn(text, result.stdout)
        self.assertNotRegex(result.stdout, r'(?i)SyntheticRolePhrase123|SCRAM|md5|password')

    def test_missing_writer(self):
        result = self.tool('roles-projection.sql', db='postgres', container=self.missing)
        self.assertEqual(result.returncode, 3)
        self.assertIn('anima_system_writer', result.stderr)
        self.assertEqual(result.stdout, '')

    def test_stale_preserved(self):
        before = self.execute('SELECT count(*) FROM public.work_claims WHERE released_at IS NULL;')
        result = self.gate()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('quiescence_verdict=PASS', result.stdout)
        self.assertIn('claims_stale=1', result.stdout)
        self.assertIn('stale_claim=abcdef01:2001-01-01', result.stdout)
        self.assertEqual(self.execute('SELECT count(*) FROM public.work_claims WHERE released_at IS NULL;'), before)
        self.assertEqual(self.execute('SELECT released_at IS NULL FROM public.work_claims;'), 't')

